data<-data.frame(x=c(0,1,2), y=c(1/4, 1/2, 1/4))
library(tidyverse)
ggplot(data, aes(x=x, xend=x, y=0, yend=y))+
  geom_segment(color="grey", size=10)+
  labs(title="이산확률변수의 분포", x="확률변수 X", y="P(X)")+
  theme_minimal()


